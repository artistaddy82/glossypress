#!/usr/bin/env node
// Generates INSERT SQL for all city BUZZ magazines from the Life Insurance site list.
// Run: node scripts/seed-magazines.js > db/seed-magazines.sql
// Then: psql $DATABASE_URL -f db/seed-magazines.sql

const fs = require('fs')
const path = require('path')

const OUTPUT_DIR = '/Users/myers/Documents/GitHub/Life Insurance/output'
const CITIES_JSON = '/Users/myers/Documents/GitHub/Life Insurance/data/us-cities-full.json'

// Load city reference for proper capitalization
const citiesRef = JSON.parse(fs.readFileSync(CITIES_JSON, 'utf8'))
const cityMap = {}
citiesRef.forEach(c => {
  cityMap[c.city.toLowerCase().replace(/\s+/g, '')] = c.city
})

// Extract city slugs from domain names
const domains = fs.readdirSync(OUTPUT_DIR).filter(d =>
  d.startsWith('lifeinsuranceagents') && d.endsWith('.com')
)

// Deterministic color palette from city name — hue spread across 360deg
function hslToHex(h, s, l) {
  s /= 100; l /= 100
  const a = s * Math.min(l, 1 - l)
  const f = n => {
    const k = (n + h / 30) % 12
    const color = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1)
    return Math.round(255 * color).toString(16).padStart(2, '0')
  }
  return `#${f(0)}${f(8)}${f(4)}`
}

function strHash(s) {
  let h = 0
  for (let i = 0; i < s.length; i++) h = (Math.imul(31, h) + s.charCodeAt(i)) | 0
  return Math.abs(h)
}

function palette(slug) {
  const hash = strHash(slug)
  const hue = hash % 360
  // primary: vivid saturated color
  const primary = hslToHex(hue, 90, 55)
  // secondary: complementary (+180)
  const secondary = hslToHex((hue + 180) % 360, 80, 50)
  // accent: triadic (+120), always bright
  const accent = hslToHex((hue + 120) % 360, 95, 62)
  // dark: near-black tinted with hue
  const dark = hslToHex(hue, 40, 8)
  // button: split complementary (+150)
  const button = hslToHex((hue + 150) % 360, 65, 35)
  return { primary, secondary, accent, dark, button }
}

function toSlug(domain) {
  return domain.replace('lifeinsuranceagents', '').replace('.com', '')
}

function toCityName(slug) {
  // Try direct match
  if (cityMap[slug]) return cityMap[slug]
  // Try title-casing the slug
  return slug.charAt(0).toUpperCase() + slug.slice(1)
}

const DEFAULT_TAGS = [
  'News', 'Events', 'Food & Drink', 'Arts', 'Nightlife', 'Community',
  'Sports', 'Business', 'Entertainment', 'Local', 'Outdoors', 'Family'
]

const lines = [
  '-- GlossyPress: City BUZZ magazines',
  '-- Auto-generated by scripts/seed-magazines.js',
  '',
]

domains.forEach(domain => {
  const slug = toSlug(domain)
  const cityName = toCityName(slug)
  const brandName = `${cityName} BUZZ`
  const magSlug = `${slug}-buzz`
  const { primary, secondary, accent, dark, button } = palette(slug)
  const tags = DEFAULT_TAGS.map(t => `"${t}"`).join(',')

  lines.push(
    `INSERT INTO magazines (slug, brand_name, color_primary, color_secondary, color_accent, color_dark, color_button, tags)` +
    ` VALUES ('${magSlug}', '${brandName.replace(/'/g, "''")}', '${primary}', '${secondary}', '${accent}', '${dark}', '${button}', ARRAY[${DEFAULT_TAGS.map(t => `'${t}'`).join(',')}])` +
    ` ON CONFLICT (slug) DO NOTHING;`
  )
})

console.log(lines.join('\n'))
console.error(`Generated ${domains.length} magazines.`)
